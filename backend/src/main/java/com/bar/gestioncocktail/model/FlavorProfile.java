package com.bar.gestioncocktail.model;

/**
 * Enumeration representing aromatic and taste profiles of cocktails,
 * enabling interactive customer discovery and recommendation matching.
 */
public enum FlavorProfile {
    /** Fresh, vibrant notes of fruits, berries, and citrus. */
    FRUITY,

    /** Peated, toasted, woody, or mezcal-like aromatic smoke. */
    SMOKY,

    /** Rich, sugary, dessert-like or honey-sweetened profile. */
    SWEET,

    /** Tangy, tart, citrus-forward, or acidic refreshing sensation. */
    SOUR,

    /** Astringent, botanical, herbal-amaro, or tonic-like bitterness. */
    BITTER,

    /** Warm, peppery, ginger, chili, or aromatic spiced accents. */
    SPICY,

    /** Botanical, leafy, grassy, minty, or garden herb character. */
    HERBAL
}
