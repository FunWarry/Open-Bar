package com.bar.gestioncocktail.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;

import java.math.BigDecimal;

/**
 * Request payload for creating an online payment transaction / PaymentIntent from mobile checkout.
 *
 * @param amount Amount to charge in establishment currency (must be strictly positive)
 * @param tip Optional tip amount for waitstaff (defaults to 0)
 * @param typeSplit Settlement split mode ('TOTALITE', 'MES_CONSOS', 'PART_EGALE', 'MONTANT_LIBRE')
 * @param guestName Optional nickname of the patron initiating the payment
 * @param itemsJson Serialized JSON of selected items when paying for specific consumptions
 * @param idempotencyKey Unique UUID generated by client to prevent duplicate payments
 * @param liberateTable Whether the patron requested to liberate the table upon 100% balance settlement
 * @param customerEmail Optional email address for automatic receipt delivery
 */
@Schema(description = "Request payload to initiate a secure online pay-at-table settlement")
public record PaymentIntentRequestDTO(
        @NotNull(message = "Payment amount is required")
        @DecimalMin(value = "0.50", message = "Minimum transaction amount is 0.50")
        @Schema(description = "Base amount to pay", example = "15.00")
        BigDecimal amount,

        @DecimalMin(value = "0.00", message = "Tip cannot be negative")
        @Schema(description = "Optional tip amount", example = "2.00")
        BigDecimal tip,

        @NotBlank(message = "Split type is required")
        @Schema(description = "Split billing mode", example = "TOTALITE")
        String typeSplit,

        @Schema(description = "Patron nickname", example = "Mathéo")
        String guestName,

        @Schema(description = "Serialized JSON of item IDs paid")
        String itemsJson,

        @NotBlank(message = "Idempotency key is required")
        @Schema(description = "Unique client-side idempotency UUID", example = "d9b2d63d-82d2-4e4b-9e8a-029bb63d59e2")
        String idempotencyKey,

        @Schema(description = "Whether to liberate the table if this settlement completes the total bill", example = "false")
        Boolean liberateTable,

        @Schema(description = "Optional customer email for digital receipt", example = "patron@example.com")
        String customerEmail
) {}
